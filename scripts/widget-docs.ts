/**
 * Fills the widget catalogue in docs/COMPOSING-SHOWS.md (between <!-- widgets:start --> and <!-- widgets:end -->)
 * from the lab's widget files, verdicts and tags (lab/tags.json), so a Claude session composing a show knows what each
 * widget is for, what it feels like and which instruments suit it.
 *
 *   npm run widget-docs               regenerate it
 *   npm run widget-docs -- --check    exit 1 when it is stale (after a lab round: new widgets, knobs or verdicts), or when
 *                                     lab/tags.json has errors; prints its warnings (widgets without tags) either way
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { readLabHarness } from '../src/widgets/lab-harness';
import { validateTags } from '../src/widgets/tags';
import type { WidgetMeta } from '../src/widgets/types';
import { type Catalogue, loadCatalogue, readLabTags, readLabTagWords } from './node/catalogue';
import { REPO } from './node/pack-io';

const DOC = join(REPO, 'docs', 'COMPOSING-SHOWS.md');
const START = '<!-- widgets:start -->', END = '<!-- widgets:end -->';

const cell = (s: string) => s.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
const num = (v: number) => `${Math.round(v * 1000) / 1000}`;

/** 'Feel: silky, longing · Suits: violin, cello · Role: base', in lab/tags.json's words (lab/tag-words.json). */
const tagLine = (m: WidgetMeta) => m.tags
  ? `Feel: ${m.tags.feel.join(', ')} · Suits: ${m.tags.instruments.join(', ')} · Role: ${m.tags.role}`
  : 'Not tagged yet.';

function catalogueBlock({ widgets, failed }: Catalogue): string {
  if (failed.length) throw new Error(`widgets that do not load: ${failed.map((f) => `${f.id} (${f.error})`).join(', ')}`);
  const drives = new Map(readLabHarness(readFileSync(join(REPO, 'lab', 'index.html'), 'utf8')).drives);
  const groups: [string, (m: WidgetMeta) => boolean][] = [
    ['Loved', (m) => m.verdict?.v === 'love'],
    ['Kept', (m) => m.verdict?.v === 'keep'],
    ['Needs work (the user rated them; use sparingly)', (m) => m.verdict?.v === 'needs work'],
    ['Not judged yet', (m) => !m.verdict],
  ];
  const out: string[] = [START, '', '_Generated by `npm run widget-docs` from `lab/tools/*.js`, the verdicts in `lab/index.html` and the tags in `lab/tags.json`; do not edit by hand._', '',
    '_Feel: synesthetic feel words (`lab/tag-words.json` says what each looks and sounds like). Suits: instruments that go well with it. Role: where it sits in a stack: **under** paints first and never darkens what is on top; **ground** paints its own canvas, so it goes first; **base** fills the picture but lets others show; **texture** is a fine ornament over the others, never the main picture (like the hairs on an arm); **lead** is the main character the eye follows, a melody (murmuration) or the low chords (rorschach); **accent** moves over a base; **top** works on whatever is below it._', ''];
  for (const [title, inGroup] of groups) {
    const list = [...widgets.values()].filter(inGroup);
    if (!list.length) continue;
    out.push(`### ${title}`, '');
    for (const m of list) {
      out.push(`#### \`${m.id}\`: ${m.name}${m.verdict?.note ? ` (${m.verdict.note})` : ''}`, '');
      if (m.blurb) out.push(cell(m.blurb), '');
      out.push(tagLine(m), '');
      if (!m.params.length) { out.push('No knobs.', ''); continue; }
      out.push('| knob | label | range | default | driven by | what it does |', '|---|---|---|---|---|---|');
      for (const q of m.params) {
        out.push(`| \`${q.key}\` | ${cell(q.label ?? q.key)} | ${num(q.min)}..${num(q.max)} | ${num(q.value)} | ${cell(drives.get(q.drive ?? '') ?? q.drive ?? 'fixed')} | ${cell(q.hint ?? '')} |`);
      }
      out.push('');
    }
  }
  out.push(END);
  return out.join('\n');
}

function fill(doc: string, block: string): string {
  const a = doc.indexOf(START), b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${DOC} has no ${START} … ${END} block`);
  return doc.slice(0, a) + block + doc.slice(b + END.length);
}

/** lab/tags.json against the vocabulary and the widget files: prints warnings, exits 1 on errors. */
function checkTags(ids: string[]): void {
  const { errors, warnings } = validateTags(readLabTags() ?? 'missing', readLabTagWords(), ids);
  for (const w of warnings) console.warn(`lab/tags.json warning: ${w}`);
  if (!errors.length) return;
  for (const e of errors) console.error(`lab/tags.json error: ${e}`);
  process.exit(1);
}

const catalogue = loadCatalogue();
checkTags([...catalogue.widgets.keys()]);
const disk = readFileSync(DOC, 'utf8').replace(/\r\n/g, '\n');
const next = fill(disk, catalogueBlock(catalogue));
if (process.argv.includes('--check')) {
  if (next !== disk) { console.error(`${DOC} is stale: run npm run widget-docs`); process.exit(1); }
  console.log('COMPOSING-SHOWS.md is up to date');
} else {
  writeFileSync(DOC, next);
  console.log(`wrote ${DOC}`);
}
